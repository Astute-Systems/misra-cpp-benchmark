#!/usr/bin/env python3
"""Regenerate docs/RULES.md, the index of every guideline and its examples.

    python3 tools/make_index.py           # rewrite docs/RULES.md
    python3 tools/make_index.py --check   # fail if docs/RULES.md is stale
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

CHAPTERS = {
    0: "Language independent issues",
    4: "General principles",
    5: "Lexical conventions",
    6: "Basic concepts",
    7: "Standard conversions",
    8: "Expressions",
    9: "Statements",
    10: "Declarations",
    11: "Declarators",
    12: "Classes",
    13: "Derived classes",
    14: "Member access control",
    15: "Special member functions",
    16: "Overloading",
    17: "Templates",
    18: "Exception handling",
    19: "Preprocessing directives",
    21: "Language support library",
    22: "Diagnostics library",
    23: "General utilities library",
    24: "Strings library",
    25: "Localization library",
    26: "Containers library",
    28: "Algorithms library",
    30: "Input/output library",
}


def first_example_files(case):
    """example number -> primary .cpp path (the file that carries the header)."""
    files = {}
    for src in common.case_sources(case):
        number = common.example_number(src)
        if number is not None and src.suffix == ".cpp" and src.stem == f"example{number}":
            files[number] = src
    return files


def render():
    rules = common.load_rules()
    out = [
        "# Guideline index",
        "",
        "Every guideline below has one or more examples. Each example holds a "
        "`violation` region (code that breaks the guideline) and, where a "
        "compliant form exists, a `compliant` region. See the "
        "[README](../README.md) for how the regions are scored.",
        "",
        "This file is generated by `python3 tools/make_index.py`; do not edit it by hand.",
        "",
    ]
    by_chapter = {}
    for rule in rules:
        by_chapter.setdefault(int(rule["id"].split(".")[0]), []).append(rule)

    total_examples = 0
    for chapter in sorted(by_chapter):
        out.append(f"## Chapter {chapter}: {CHAPTERS.get(chapter, '')}".rstrip(": "))
        out.append("")
        out.append("| Guideline | Category | Title | Examples |")
        out.append("| --- | --- | --- | --- |")
        for rule in by_chapter[chapter]:
            case = common.CASES / rule["directory"]
            descriptions = common.example_descriptions(case)
            files = first_example_files(case)
            total_examples += len(files)
            kind = "Dir" if rule["kind"] == "Dir" else "Rule"
            links = []
            for number in sorted(files):
                rel = f"../cases/{rule['directory']}/{files[number].name}"
                text = descriptions.get(number, "").replace("|", "\\|")
                links.append(f"[{number}]({rel}) {text}")
            title = rule["title"].replace("|", "\\|")
            out.append(f"| {kind} {rule['id']} | {rule['category']} | {title} | "
                       + "<br>".join(links) + " |")
        out.append("")
    out.append(f"{len(rules)} guidelines, {total_examples} examples.")
    return "\n".join(out) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/RULES.md is out of date")
    args = parser.parse_args(argv)

    target = common.ROOT / "docs" / "RULES.md"
    text = render()
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print("docs/RULES.md is out of date; run python3 tools/make_index.py", file=sys.stderr)
            return 1
        print("docs/RULES.md is up to date")
        return 0
    target.parent.mkdir(exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
